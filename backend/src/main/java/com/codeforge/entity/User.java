package com.codeforge.entity;

import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * JPA entity representing a CodeForge user account.
 *
 * <p>Maps to the {@code users} table in the underlying database (SQL Server / H2).
 * Stores identity credentials, authorization roles, and gamified telemetry data
 * (daily active coding streaks, solved problem counts, aggregate acceptance rate, and practice hours).</p>
 *
 * <p><strong>Database Constraints:</strong></p>
 * <ul>
 *   <li>{@code username}: Unique, non-null, maximum 100 characters.</li>
 *   <li>{@code email}: Unique, non-null, maximum 255 characters.</li>
 *   <li>{@code passwordHash}: Non-null BCrypt hash string.</li>
 * </ul>
 */
@Entity
@Table(name = "users")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class User {

    /**
     * Primary key identifier for the user account (auto-incremented identity).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Unique login handle chosen by the user (e.g., "alex_morgan").
     */
    @Column(nullable = false, unique = true, length = 100)
    private String username;

    /**
     * Unique email address used for communication and authentication.
     */
    @Column(nullable = false, unique = true, length = 255)
    private String email;

    /**
     * Cryptographic hash of the user's password generated by {@link org.springframework.security.crypto.password.PasswordEncoder}.
     */
    @Column(nullable = false, length = 255)
    private String passwordHash;

    /**
     * Full display name of the user (e.g., "Alex Morgan").
     */
    @Column(nullable = false, length = 150)
    private String fullName;

    /**
     * Authorization role for role-based access control (e.g., 'Guest', 'Learner', 'Admin').
     */
    @Column(length = 50)
    @Builder.Default
    private String role = "Learner";

    /**
     * Consecutive active practice days count displayed on the user dashboard.
     */
    @Builder.Default
    private Integer streakDays = 7;

    /**
     * Total number of coding challenges solved successfully with an Accepted submission.
     */
    @Builder.Default
    private Integer solvedCount = 48;

    /**
     * Overall submission acceptance percentage (accepted / total submissions * 100).
     */
    @Builder.Default
    private BigDecimal acceptanceRate = new BigDecimal("76.20");

    /**
     * Cumulative active practice time spent inside the CodeForge IDE in hours.
     */
    @Builder.Default
    private BigDecimal practiceTimeHours = new BigDecimal("12.50");

    /**
     * Timestamp recording when the user account was registered.
     */
    @Builder.Default
    private LocalDateTime createdAt = LocalDateTime.now();
}
