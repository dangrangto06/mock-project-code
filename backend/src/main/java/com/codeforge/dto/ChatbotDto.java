package com.codeforge.dto;

import jakarta.validation.constraints.NotBlank;
import lombok.*;

import java.time.LocalDateTime;
import java.util.List;

/**
 * Data Transfer Objects for CodeForge AI Chatbot operations.
 */
public class ChatbotDto {

    /**
     * Inbound question payload sent to the chatbot.
     */
    @Getter
    @Setter
    @NoArgsConstructor
    @AllArgsConstructor
    @Builder
    public static class ChatRequest {
        @NotBlank(message = "Message cannot be empty")
        private String message;

        private String conversationId;

        private String contextPage; // e.g. "ide", "library", "notes", "community", "dashboard"
    }

    /**
     * Outbound response generated by the chatbot.
     */
    @Getter
    @Setter
    @NoArgsConstructor
    @AllArgsConstructor
    @Builder
    public static class ChatResponse {
        private String reply;

        private boolean inScope;

        private String relevantRoute; // e.g. "ide", "library", "notes", "community", "admin"

        private List<String> suggestedPrompts;

        private String conversationId;
    }

    /**
     * Individual message record in conversation history.
     */
    @Getter
    @Setter
    @NoArgsConstructor
    @AllArgsConstructor
    @Builder
    public static class MessageItem {
        private Long id;
        private String sender; // "user" or "bot"
        private String message;
        private boolean inScope;
        private String relevantRoute;
        private LocalDateTime createdAt;
    }

    /**
     * Conversation history response list.
     */
    @Getter
    @Setter
    @NoArgsConstructor
    @AllArgsConstructor
    @Builder
    public static class ChatHistoryResponse {
        private String conversationId;
        private List<MessageItem> messages;
    }
}
